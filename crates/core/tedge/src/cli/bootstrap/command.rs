    /// Request username/password device credentials (basic auth)
    ///
    /// Polls the device credentials endpoint until an operator accepts
    /// the registration request, stores the credentials at
    /// `c8y.credentials_path` (mode 600), and switches `c8y.auth_method`
    /// to `basic` so the bridge and mapper use them.
    /// The value of a registration-method input:
    /// collected by the wizard or applied as a declared default (hook_envs),
