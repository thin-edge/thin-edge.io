    fn input_value(&self, env: &str) -> Option<String> {
        self.hook_envs
            .iter()
            .find(|(name, _)| name == env)
            .map(|(_, value)| value.clone())
            .or_else(|| std::env::var(env).ok().filter(|value| !value.is_empty()))
    }

    /// Store pre-registered device credentials (basic auth).
    ///
    /// No cloud exchange: the operator supplies the issued
    /// username/password (`basic-preregistered` method inputs),
    /// so registration also completes offline -
    /// the staged services then connect by themselves
    /// on first network contact
    async fn register_basic_preregistered(
        &self,
        config: &TEdgeConfig,
    ) -> Result<(), MaybeFancy<anyhow::Error>> {
        let c8y_config =
            config.mapper_config::<C8yMapperSpecificConfig>(&self.profile().cloned())?;
        let configured: Utf8PathBuf = c8y_config.cloud_specific.credentials_path.clone().into();
        let legacy_default = self.config_dir.join("credentials.toml");
        let (credentials_path, persist_credentials_path) = if configured == legacy_default {
            let mapper_dir = match self.profile() {
                None => "c8y".to_owned(),
                Some(profile) => format!("c8y.{profile}"),
            };
            (
                self.config_dir
                    .join("mappers")
                    .join(mapper_dir)
                    .join("credentials.toml"),
                true,
            )
        } else {
            (configured, false)
        };

        let mut registered_device_id = None;
        if credentials_path.exists() {
            self.detail(&format!(
                "credentials already present at {credentials_path}, skipping"
            ));
            let effective_id = self
                .device_id
                .clone()
                .or_else(|| c8y_config.device.id().ok().map(|id| id.to_string()));
            self.warn_credentials_mismatch(&credentials_path, effective_id.as_deref())
                .await;
        } else if self.dry_run {
            self.ui.line(&format!(
                "would store the pre-registered device credentials at {credentials_path}"
            ));
        } else {
            let credentials = self.preregistered_credentials()?;
            let device_id = self.resolve_preregistered_device_id(&credentials)?;
            if self.offline {
                self.detail("offline: skipping the credentials verification");
            } else if let Ok(host) = c8y_config.cloud_specific.http.or_config_not_set() {
                let http_config = config.cloud_root_certs().await?;
                self.verify_device_credentials(&host.to_string(), &credentials, &http_config)
                    .await?;
            }
            basic::store_credentials(&credentials_path, &credentials).await?;
            self.ui
                .line(&format!("credentials stored at {credentials_path}"));
            registered_device_id = Some(device_id);
        }

        // Same local configuration as the basic exchange:
        // the auth switch, the credentials location, and the device id
        // the credentials belong to (required as the MQTT client id)
        let mut updates = vec![self.config_key("auth_method", "basic".to_owned())];
        if persist_credentials_path {
            updates.push(self.config_key("credentials_path", credentials_path.to_string()));
        }
        if let Some(device_id) = registered_device_id.or(self.device_id.clone()) {
            updates.push(KeyValue {
                key: "device.id".to_owned(),
                value: device_id,
            });
        }
        for update in &updates {
            self.detail(&format!(
                "{} {}={}",
                if self.dry_run { "would set" } else { "set" },
                update.key,
                update.value
            ));
        }
        if !self.dry_run {
            let config = self.load_config().await?;
            apply_tedge_config_updates(config, &updates).await?;
        }
        Ok(())
    }

